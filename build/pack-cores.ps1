<#
    Packs the downloadable engines and rewrites the catalogues to match.

    An engine that is not in the installer arrives from a release asset, and the app will not load
    one whose SHA-256 differs from what the catalogue claims. So the zip and the catalogue have to
    be made together, by one thing, or the next release ships a catalogue describing the previous
    build and every download fails verification.

    Run before publishing a release, then upload dist\cores\* as assets of the tag named below and
    commit the updated cores-catalog\*.json.

    Usage:  powershell -ExecutionPolicy Bypass -File build\pack-cores.ps1 [-Tag cores-2026.09]
#>
param(
    # The branch that carries the engines. A branch of its own, not master: the binaries are
    # megabytes and they change on their own schedule, so keeping them out of the app's history
    # means a core can be republished without touching a line of the app — and the app's history
    # does not carry a copy of every engine it ever shipped.
    [string]$Branch = 'cores',
    [string]$Repo = 'YounikarYounhard/MoonInternet'
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$out = Join-Path $root 'dist\cores'
New-Item -ItemType Directory -Force -Path $out | Out-Null

function Publish($id, $version, $file, $path, $catalogue) {
    $zip = Join-Path $out $file
    if (Test-Path $zip) { Remove-Item $zip -Force }
    if ($path -like '*.so') { Copy-Item $path $zip -Force }        # already one file: ship it as is
    else { Compress-Archive -Path (Join-Path $path '*') -DestinationPath $zip -Force }

    $hash = (Get-FileHash $zip -Algorithm SHA256).Hash.ToLower()
    $size = (Get-Item $zip).Length
    Write-Host ("{0,-10} {1,10:N0} bytes  {2}" -f $id, $size, $hash) -ForegroundColor Green

    $json = [ordered]@{
        '_'     = 'Generated by build/pack-cores.ps1 - edit the script, not this file.'
        'cores' = @([ordered]@{
            id      = $id
            version = $version
            file    = $file
            size    = $size
            sha256  = $hash
            url     = "https://raw.githubusercontent.com/$Repo/$Branch/$file"
        })
    }
    $dest = Join-Path $root "cores-catalog\$catalogue"
    New-Item -ItemType Directory -Force -Path (Split-Path $dest) | Out-Null
    [IO.File]::WriteAllText($dest, ($json | ConvertTo-Json -Depth 5), (New-Object Text.UTF8Encoding $false))
}

# The engine commit awgproxy is built against; see build-awgproxy.ps1 for why it is not a tag.
$awgVersion = '3.1-b5928ef'

Publish 'awg' $awgVersion 'awg.zip' (Join-Path $root 'cores\awg') 'windows-x64.json'

$androidSo = Join-Path $root 'dist\cores\android\arm64-v8a\libawgproxy.so'
if (Test-Path $androidSo) {
    Publish 'awg' $awgVersion 'libawgproxy.so' $androidSo 'android-arm64.json'
} else {
    Write-Host "missing $androidSo - run build\build-awgproxy.ps1 -Android first" -ForegroundColor Yellow
}

Write-Host "`nAssets in $out - publish them on the '$Branch' branch together with the catalogues." -ForegroundColor Cyan
